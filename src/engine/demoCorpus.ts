function makeDemoSample(
  raw: Omit<
    TextSample,
    'normalized_text' | 'content_hash' | 'linguistic_metrics'
  >
): TextSample {
  return {
    ...raw,
    normalized_text: normalizeUnicodeText(raw.text),
    content_hash: computeContentHash(raw.text),
    linguistic_metrics: analyzeTextLinguistics(raw.text),
  };
}

